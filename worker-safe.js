function numericRange(values) {
  let min = Infinity;
  let max = -Infinity;
  let hasValues = false;
  for (const value of values) {
    hasValues = true;
    if (value < min) min = value;
    if (value > max) max = value;
  }
  return hasValues ? { min, max } : null;
}
