import esbuild from "esbuild";
import process from "process";
import { builtinModules, createRequire } from "node:module";
import { dirname, join } from "node:path";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");
const watchMode = (process.argv[2] === "watch");

const commonOptions = {
	banner: {
		js: banner,
	},
	bundle: true,
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	// @bokuweb/zstd-wasm's web build evaluates new URL("./zstd.wasm", import.meta.url)
	// during init even when the WASM bytes are passed in. import.meta.url is undefined
	// in CJS output, which would throw; any valid URL satisfies it (never fetched).
	define: { "import.meta.url": '"file:///places-shared"' },
};

const hostExternal = [
	"obsidian",
	"electron",
	"@codemirror/autocomplete",
	"@codemirror/collab",
	"@codemirror/commands",
	"@codemirror/language",
	"@codemirror/lint",
	"@codemirror/search",
	"@codemirror/state",
	"@codemirror/view",
	"@lezer/common",
	"@lezer/highlight",
	"@lezer/lr",
	...builtinModules,
];

// One library, one bundle.
//
// src/main.ts is the barrel over every domain (place, units, geo, polyline,
// overlay, map, settings, services, render, utils, ui), and package.json maps
// EVERY domain subpath to this single output. Source keeps importing
// `places-shared/map`, `places-shared/utils` and so on because that stays
// readable and the per-subpath .d.ts still narrows what a consumer sees - but at
// runtime all of them resolve here, so a consuming plugin bundles exactly one
// copy no matter how many subpaths it imports.
//
// Do not reintroduce per-domain outputs. They were self-contained bundles with
// no shared chunk, so any module used by two domains was copied into both:
// DistanceCalculator alone landed in six outputs and 6-7 copies per plugin, and
// because each copy had its own module scope, module-level state could not be a
// singleton. That is the whole reason CrossBundleRegistry has to hoist shared
// state onto globalThis.
const mainContext = await esbuild.context({
	...commonOptions,
	entryPoints: ["src/main.ts"],
	external: hostExternal,
	outfile: "main.js",
});

// Worker-safe bundle (no obsidian dependencies).
// Stays separate: it is loaded inside the frequency-analysis Web Worker, which
// cannot see the host modules main.js externalizes.
const workerSafeContext = await esbuild.context({
	...commonOptions,
	entryPoints: ["src/worker-safe.ts"],
	// Worker-safe code must be completely self-contained. Do not externalize
	// host or Node modules: accidental imports should fail this build.
	outfile: "worker-safe.js",
});

// Compression bundle (zstd WASM codec).
// Stays separate on purpose: it inlines ~345 KB of WASM and only the two plugins
// that decode overlay data (places, places-environment) import it. Folding it
// into main.js would put that payload in all sixteen plugins. Everything else
// reaches compression through StringCompressor, which lives in utils and is
// therefore already part of main.js.
// The package's exports map only exposes its root entry, so the .wasm asset
// cannot be imported by bare specifier; resolve the entry and walk to the asset.
const require = createRequire(import.meta.url);
const zstdWasmPath = join(dirname(require.resolve("@bokuweb/zstd-wasm")), "..", "web", "zstd.wasm");

// Maps the zstd-wasm-binary virtual specifier (declared in src/globals.d.ts) to
// the installed package's wasm binary; the binary loader inlines it as base64
// and decodes it to a Uint8Array at load time.
const zstdWasmBinaryPlugin = {
	name: "zstd-wasm-binary",
	setup(build) {
		build.onResolve({ filter: /^zstd-wasm-binary$/ }, () => ({ path: zstdWasmPath }));
	},
};

const compressionContext = await esbuild.context({
	...commonOptions,
	entryPoints: ["src/compression/index.ts"],
	external: hostExternal,
	outfile: "compression.js",
	plugins: [zstdWasmBinaryPlugin],
	loader: { ".wasm": "binary" },
});

const contexts = [mainContext, workerSafeContext, compressionContext];

if (watchMode) {
	await Promise.all(contexts.map(context => context.watch()));
} else {
	await Promise.all(contexts.map(context => context.rebuild()));
	process.exit(0);
}
